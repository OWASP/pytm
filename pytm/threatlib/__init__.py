__all__ = [
    *(cls.__name__ for cls in BUILTIN_THREATS),
    "BUILTIN_THREATS",
    "iter_builtin_threat_classes",
]


def iter_builtin_threat_classes() -> Iterator[type[Threat]]:
    """Yield the active built-in Threat subclasses in evaluation order."""
    for cls in BUILTIN_THREATS:
        if not getattr(cls, "DEPRECATED", None):
            yield cls
